use serde_json::Value;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InputKind {
    Combo,
    Checkbox,
    Entry,
    /// Saved for compatibility, but never restored as authoritative input.
    Label,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InitialValue {
    Bool(bool),
    Text(&'static str),
}

impl InitialValue {
    pub fn to_value(self) -> Value {
        match self {
            Self::Bool(value) => Value::Bool(value),
            Self::Text(value) => Value::String(value.to_owned()),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct InputSpec {
    pub key: &'static str,
    pub kind: InputKind,
    /// Position in the complete legacy widget walk, not a compact key index.
    pub walk_order: usize,
    pub initial: InitialValue,
    pub choices: &'static [&'static str],
    pub attribute_paths: &'static [&'static str],
}

impl InputSpec {
    pub fn initial_value(&self) -> Value {
        self.initial.to_value()
    }
}

